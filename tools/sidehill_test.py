# Score start screen: 'Tip: side hill shots' card shows on field and 3D (ABA) rounds only, closed by default, expands, stays out of the scorer. 390x844.
import subprocess,sys,time,os
from playwright.sync_api import sync_playwright
ok=[];bad=[]
def chk(n,c):(ok if c else bad).append(n)
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
srv=subprocess.Popen([sys.executable,'-m','http.server','8778'],cwd=ROOT,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL);time.sleep(1)
try:
 with sync_playwright() as p:
  b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox']);pg=b.new_page(viewport={'width':390,'height':844})
  errs=[];pg.on('pageerror',lambda e:errs.append(str(e)));pg.on('console',lambda m:m.type=='error' and errs.append(m.text));pg.on('dialog',lambda d:d.accept())
  pg.goto('http://localhost:8778/?tester=nathe');pg.wait_for_timeout(1200);pg.evaluate("S.unlocked=true;save()");pg.reload();pg.wait_for_timeout(2500)
  E=pg.evaluate;E("nav('score')");pg.wait_for_timeout(500);E("cur=null;sv='sheet';score()");pg.wait_for_timeout(300)
  opts=pg.eval_on_selector_all('#rd option','o=>o.map(x=>x.value)')
  fld=E("Object.keys(ROUNDS).find(r=>!ROUNDS[r].custom&&!ROUNDS[r].legacy&&!ROUNDS[r].aba&&isFld(faceR(ROUNDS[r],0)))")
  aba=E("Object.keys(ROUNDS).find(r=>!ROUNDS[r].custom&&!ROUNDS[r].legacy&&ROUNDS[r].aba)")
  tgt=E("Object.keys(ROUNDS).find(r=>!ROUNDS[r].custom&&!ROUNDS[r].legacy&&!ROUNDS[r].aba&&!isFld(faceR(ROUNDS[r],0))&&/70m|WA 720|18m/.test(r))")
  chk('rounds found: '+str([fld,aba,tgt]),fld in opts and aba in opts and tgt in opts)
  def sel(r):pg.select_option('#rd',r);pg.wait_for_timeout(200)
  sel(tgt);chk('no tip on target round',pg.locator('#sidehill').count()==0)
  sel(fld);chk('tip on field round',pg.locator('#sidehill').count()==1)
  chk('closed by default, one-line label',not E("document.querySelector('#sidehill').open") and pg.inner_text('#sidehill summary')=='Tip: side hill shots' and pg.locator('#sidehill').bounding_box()['height']<30)
  pg.click('#sidehill summary');pg.wait_for_timeout(200)
  t=pg.inner_text('#sidehill')
  chk('expands with exact text',E("document.querySelector('#sidehill').open") and 'Side hill shots: keep the bow level' in t and pg.locator('#sidehill li').count()==5 and "You don't need to watch the bubble for the rest of the shot." in t and 'Twisting the bow level at full draw sets the shot up to miss the other way.' in t)
  chk('no nock tuning',('nock' not in pg.inner_text('#app').lower()))
  chk('no horizontal overflow',E('document.querySelector("#scroller").scrollWidth<=390'))
  bb=pg.locator('#sidehill').bounding_box();st=pg.locator('#st').bounding_box()
  chk('Start button below the open tip, not covered',st['y']>=bb['y']+bb['height'])
  pg.screenshot(path='/tmp/sidehill_field.png',full_page=True)
  sel(aba);chk('tip on 3D/ABA round',pg.locator('#sidehill').count()==1)
  sel(tgt);chk('tip gone when switching back to target',pg.locator('#sidehill').count()==0)
  sel(fld);pg.click('#st');pg.wait_for_timeout(400)
  chk('tip not inside the field scorer (keypad clear)',pg.locator('#sidehill').count()==0 and pg.locator('.ad-pad').count()==1)
  E("cur=null;sv='sheet';score()");pg.wait_for_timeout(300);sel(aba);pg.click('#sidehill summary');pg.screenshot(path='/tmp/sidehill_aba.png',full_page=True);pg.click('#st');pg.wait_for_timeout(400)
  chk('tip not inside the ABA scorer',pg.locator('#sidehill').count()==0 and pg.locator('[data-z]').count()>0)
  chk('no page errors '+str(errs[:3]),not errs)
  b.close()
finally:srv.terminate()
for n in ok:print('PASS',n)
for n in bad:print('FAIL',n)
print(f'{len(ok)}/{len(ok)+len(bad)}');sys.exit(1 if bad else 0)
